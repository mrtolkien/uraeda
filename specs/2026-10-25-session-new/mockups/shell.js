/** A row of a nav pane: icon, title and its step, its mark. */
const entry = ([ic, title, meta, mark, counts], current) => `
  <div class="entry${current ? " current" : ""}">
    ${icon(ic)}
    <span>${title}<span class="meta">${meta}</span></span>
    ${mark}
    <span class="sub">${icon("ellipsis")}</span>
    ${counts ? `<span class="counts"><span class="green">+${counts[0]}</span> <span class="red">-${counts[1]}</span></span>` : ""}
  </div>`;

